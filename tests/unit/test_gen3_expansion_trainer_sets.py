def _adapter() -> Gen3ExpansionAdapter:
    return Gen3ExpansionAdapter(rom_type=ROM_TYPE)


def _pack() -> dict:
    return json.loads(_JSON_PACK.read_text(encoding="utf-8"))


def test_trainer_info_and_party_for_a_gym_leader():
    a = _adapter()
    data = _pack()
    tid, roxanne = next((int(k), v) for k, v in data["trainers"].items() if v["const"] == "TRAINER_ROXANNE_1")
    assert a.trainer_info(tid) == ("Roxanne", "Leader")
    party = a.trainer_party(tid)
    assert party == roxanne["party"]
    assert [p["species"] for p in party] == ["Geodude", "Geodude", "Nosepass"]


def test_no_base_name_maps_to_more_than_one_trainer_index():
    """OMP cx-081c78d3 F1 falsifier: the Prep tab groups a vendored setdex key by the text
    before " | " (calc/src/js/slink_bridge.js's _buildTrainerIndex); if two different trainer
    ids ever produced the same base text, their parties would silently merge into one fake
    combined encounter (this is exactly what happened before compute_bases() -- a rematch
    tier's discriminator sat after the pipe, an opaque uniqueness key the Prep tab never reads
    for grouping)."""
    dex = _js_setdex_dict()
    base_to_indexes: dict[str, set] = {}
    for sets in dex.values():
        for key, entry in sets.items():
            pipe = key.find(" | ")
            base = key[:pipe].strip() if pipe != -1 else key
            base_to_indexes.setdefault(base, set()).add(entry["index"])
    collisions = {b: idx for b, idx in base_to_indexes.items() if len(idx) > 1}
    assert not collisions


def test_trainers_by_area_keys_are_client_emittable_areas():
    """Derived-data oracle (OMP cx-081c78d3 F3/F4): every area gen3_exp_trainers.json groups key
    trainers under must be an area id the Lua client can actually emit
    (data/games/gen3_exp/28877d73/gen3_exp_areas.lua's values), never a made-up or stale one."""
    data = _pack()
    lua_text = _AREAS_LUA.read_text(encoding="utf-8")
    valid_areas = set(re.findall(r'=\s*"([^"]+)"', lua_text))
    assert data["trainers_by_area"], "expected at least one area with key trainers"
    for area in data["trainers_by_area"]:
        assert area in valid_areas, area


def test_every_key_trainers_by_area_entry_is_flagged_key_and_matches_its_area():
    """Replaces the old mirror test (asserted the pack against itself): cross-checks
    trainers_by_area against the per-trainer records it was built from, and against the live
    adapter, independently of trusting either side alone."""
    a = _adapter()
    data = _pack()
    for area, tids in data["trainers_by_area"].items():
        assert tids, area
        for tid in tids:
            t = data["trainers"][str(tid)]
            assert t.get("key") is True
            assert t.get("area") == area
        assert sorted(a.trainers_for_area(area)) == sorted(tids)


def test_every_key_trainer_level_cap_equals_max_party_level():
    """Derived-data oracle (OMP cx-081c78d3 F3): level_cap is documented as "the trainer's own
    highest party level" -- prove it, for every key trainer, not just the Champion."""
    data = _pack()
    checked = 0
    for t in data["trainers"].values():
        if not t.get("key"):
            continue
        assert t["level_cap"] == max(p["level"] for p in t["party"])
        checked += 1
    assert checked > 0


def test_trainers_pack_is_lazy_loaded():
    """OMP cx-081c78d3 F8: constructing the adapter (what calc_profile()/a Manager render does)
    must not parse the ~40k-line trainers pack; only a trainer_* call should."""
    _gen3_expansion_mod._load_trainers_pack.cache_clear()
    try:
        a = Gen3ExpansionAdapter(rom_type=ROM_TYPE)
        assert _gen3_expansion_mod._load_trainers_pack.cache_info().currsize == 0
        assert a.calc_profile() is not None
        assert _gen3_expansion_mod._load_trainers_pack.cache_info().currsize == 0
        a.trainer_info(1)
        assert _gen3_expansion_mod._load_trainers_pack.cache_info().currsize == 1
    finally:
        _gen3_expansion_mod._load_trainers_pack.cache_clear()


def test_trainers_pack_source_mismatch_fails_closed(tmp_path, monkeypatch):
    """OMP cx-081c78d3 F7: a trainers pack whose source.commit doesn't match
    data/gen3_exp_sources.lock.json must raise, never serve stale/wrong data quietly."""
    bad = json.loads(_JSON_PACK.read_text(encoding="utf-8"))
    bad["source"]["commit"] = "0" * 40
    bad_path = tmp_path / "gen3_exp_trainers.json"
    bad_path.write_text(json.dumps(bad), encoding="utf-8")
    monkeypatch.setattr(_gen3_expansion_mod, "TRAINERS_PACK", bad_path)
    _gen3_expansion_mod._load_trainers_pack.cache_clear()
    try:
        with pytest.raises(ValueError):
            _gen3_expansion_mod._load_trainers_pack()
    finally:
        _gen3_expansion_mod._load_trainers_pack.cache_clear()
