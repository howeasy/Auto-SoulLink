"""Falsifier for the pokeemerald-expansion trainer sets (card XC4).

Mirrors tests/unit/test_calc_trainer_sets.py's species+level whole-file multiset check: parses
the PINNED expansion source directly (independent of tools/gen_gen3_exp_trainers.py's own
block-based parser -- a flat regex scan is the "ground truth from the decomp, not from a second
copy" this repo's other trainer-set tests already use) and checks it against both generated
outputs: the vendored calc setdex (calc/src/js/data/sets/games/EmeraldExpansion.js) and the
trainer-panel data pack (data/games/gen3_exp/28877d73/gen3_exp_trainers.json).

OMP cx-081c78d3 F3 extended this beyond species+level: held item, nature and IVs are always
explicit in this build (checked full-equality, whole-file multiset, same style as species+level);
explicit .moves are checked too, but only as a SUBSET (a mon with no .moves gets the level-up
learnset default instead, and the JSON pack doesn't record which branch produced its "moves" list,
so a full-multiset equality on moves would conflate the two) -- see
test_explicit_moves_in_source_all_appear_in_the_json_pack and, for the default branch,
test_default_derived_moves_match_a_learnset_sample. Ponytail note: this does not repeat the
full-fidelity comparison a second time for the JS setdex (calc/src/js/...); that file is derived
from the exact same in-process `trainers` dict as the JSON pack in one tools/gen_gen3_exp_trainers.py
run, so a JSON-pack fidelity bug would already be visible here -- add a JS-side copy only if the
two outputs are ever generated by separate passes.

The pinned source (data/gen3_exp_sources.lock.json: tag expansion/1.17.0, commit
e8bd1cd7b03fc032ea37e3ecd38b379b5d01a1e7) lives only on the build host (ssh hgbox, ~/slink-exp)
-- never checked into this repo -- so most runs of this file hit the "source not found" skip.
Point SLINK_EXPANSION_SRC at a local copy (or a `.cache/expansion/<commit>` checkout under the
repo, same walk-up convention as pret) to run the source-comparison tests for real: an absent
source is a named skip, but a PRESENT source at the wrong commit is a hard failure, never a
silent pass -- the whole point of pinning.

The adapter tests at the bottom need no pinned source: they exercise the shipped data pack
directly. Only test_trainer_info_and_party_for_a_gym_leader is a literal (hardcoded) check; the
rest are derived-data oracles (OMP cx-081c78d3 F4 -- the previous trio just re-read the pack and
asserted it against itself, which can't fail when the generator itself is wrong).
"""
