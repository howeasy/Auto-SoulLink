def test_no_base_name_maps_to_more_than_one_trainer_index():
    """OMP cx-081c78d3 F1 falsifier: the Prep tab groups a vendored setdex key by the text
    before " | " (calc/src/js/slink_bridge.js's _buildTrainerIndex); if two different trainer
    ids ever produced the same base text, their parties would silently merge into one fake
    combined encounter (this is exactly what happened before compute_bases() -- a rematch
    tier's discriminator sat after the pipe, an opaque uniqueness key the Prep tab never reads
    for grouping)."""
    dex = _js_setdex_dict()
    base_to_indexes: dict[str, set] = {}
    for sets in dex.values():
        for key, entry in sets.items():
            pipe = key.find(" | ")
            base = key[:pipe].strip() if pipe != -1 else key
            base_to_indexes.setdefault(base, set()).add(entry["index"])
    collisions = {b: idx for b, idx in base_to_indexes.items() if len(idx) > 1}
    assert not collisions


