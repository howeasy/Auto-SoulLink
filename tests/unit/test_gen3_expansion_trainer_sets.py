import pytest

_REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_REPO))

from server.adapters import gen3_expansion as _gen3_expansion_mod  # noqa: E402
from server.adapters.gen3_expansion import ROM_TYPE, Gen3ExpansionAdapter  # noqa: E402
from server.adapters.gen3_frlge import default_moves  # noqa: E402
from tools.gen_gen3_exp_trainers import (  # noqa: E402
    enum_values,
    parse_learnset_tables,
    parse_species_learnset_symbols,
    pretty,
)

_LOCK = json.loads((_REPO / "data/gen3_exp_sources.lock.json").read_text(encoding="utf-8"))
_PIN = _LOCK["source"]["commit"]
_JSON_PACK = _REPO / "data/games/gen3_exp/28877d73/gen3_exp_trainers.json"
_JS_SETDEX = _REPO / "calc/src/js/data/sets/games/EmeraldExpansion.js"
_AREAS_LUA = _REPO / "data/games/gen3_exp/28877d73/gen3_exp_areas.lua"


def _canon(s: str) -> str:
    """Fold a species name down to bare lowercase alnum -- sidesteps SPECIES_MR_MIME vs
    "Mr. Mime" / "Nidoran-F" vs SPECIES_NIDORAN_F without a per-name exceptions table."""
    return re.sub(r"[^a-z0-9]", "", s.lower())


def _find_expansion_src() -> Path | None:
    env = os.environ.get("SLINK_EXPANSION_SRC")
    if env:
        return Path(env)
    d = _REPO
    for _ in range(6):
        cand = d / ".cache" / "expansion" / _PIN
        if cand.is_dir():
            return cand
        parent = d.parent
        if parent == d:
            break
        d = parent
    return None


def _git_head(path: Path) -> str | None:
    r = subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def _need_source() -> Path:
    src = _find_expansion_src()
    if src is None:
        pytest.skip(f"pokeemerald-expansion checkout not found (set SLINK_EXPANSION_SRC; pin {_PIN})")
    head = _git_head(src)
    assert head == _PIN, f"{src} is at {head}, not the pin {_PIN} (data/gen3_exp_sources.lock.json)"
    return src


def _source_full_records(src: Path) -> list[dict]:
    """Independent (not tools/gen_gen3_exp_trainers.py's block parser) flat scan of every mon in
    src/data/trainers.h: species+level (as before), plus whichever of .heldItem/.nature/.iv/
    .moves appear anywhere in that mon's block before the NEXT mon's .species begins -- the
    window spans from THIS mon's own .species (field order varies per mon: .iv sometimes comes
    before .lvl, sometimes after) up to the next ".species", so a later mon's fields are never
    misattributed to an earlier one and an earlier field is never missed. "moves" is None when
    the source has no explicit .moves for that mon (the level-up-learnset default applies
    instead -- see test_default_derived_moves_match_a_learnset_sample)."""
    text = re.sub(r"#line \d+\n\s*", "", (src / "src/data/trainers.h").read_text(encoding="utf-8"))
    species_ids = enum_values((src / "include/constants/species.h").read_text(encoding="utf-8"), "SPECIES_")
    move_ids = enum_values((src / "include/constants/moves.h").read_text(encoding="utf-8"), "MOVE_")
    item_ids = enum_values((src / "include/constants/items.h").read_text(encoding="utf-8"), "ITEM_")
    adapter = Gen3ExpansionAdapter(rom_type=ROM_TYPE)
    records = []
    for m in re.finditer(r"\.species\s*=\s*(SPECIES_\w+),.{1,300}?\.lvl\s*=\s*(\d+),", text, re.S):
        sid = species_ids.get(m[1])
        if sid is None:
            continue
        window = text[m.start():m.start() + 700]
        nxt = window.find(".species", len(".species"))
        if nxt != -1:
            window = window[:nxt]
        item_m = re.search(r"\.heldItem\s*=\s*(ITEM_\w+)", window)
        item = None
        if item_m and item_m[1] != "ITEM_NONE":
            iid = item_ids.get(item_m[1])
            item = adapter.calc_name("item", adapter.item_name(iid)) if iid else item_m[1]
        nat_m = re.search(r"\.nature\s*=\s*NATURE_(\w+)", window)
        nature = pretty(nat_m[1].replace("_", " ").lower()) if nat_m else None
        iv_m = re.search(r"\.iv\s*=\s*TRAINER_PARTY_IVS\(([^)]*)\)", window)
        ivs = None
        if iv_m:
            parts = [int(x.strip()) for x in iv_m[1].split(",")]
            if len(parts) == 6:
                hp, atk, df, spe, spa, spd = parts
                ivs = (("atk", atk), ("def", df), ("hp", hp), ("spa", spa), ("spd", spd), ("spe", spe))
        mv_m = re.search(r"\.moves\s*=\s*\{([^}]*)\}", window)
        moves = None
        if mv_m:
            macros = [mm.strip() for mm in mv_m[1].split(",") if mm.strip() and mm.strip() != "MOVE_NONE"]
            moves = tuple(adapter.calc_name("move", adapter.move_name(move_ids[mo])) if mo in move_ids else mo
                          for mo in macros)
        records.append({
            "species": _canon(adapter.calc_species(sid)), "level": int(m[2]),
            "item": item, "nature": nature, "ivs": ivs, "moves": moves,
        })
    return records


def _source_species_level_multiset(src: Path) -> Counter:
    return Counter((r["species"], r["level"]) for r in _source_full_records(src))


def _source_full_multiset(src: Path) -> Counter:
    """species+level+item+nature+ivs -- all always explicit or always None-if-absent in this
    build, so this is a full-equality multiset (unlike moves, see the module docstring)."""
    return Counter((r["species"], r["level"], r["item"], r["nature"], r["ivs"]) for r in _source_full_records(src))


def _source_explicit_moves_multiset(src: Path) -> Counter:
    return Counter((r["species"], r["level"], r["item"], r["nature"], r["ivs"], r["moves"])
                   for r in _source_full_records(src) if r["moves"] is not None)


def _json_pack_multiset() -> Counter:
    data = json.loads(_JSON_PACK.read_text(encoding="utf-8"))
    c: Counter = Counter()
    for t in data["trainers"].values():
        for mon in t["party"]:
            c[(_canon(mon["species"]), mon["level"])] += 1
    return c


def _json_pack_mon_key(mon: dict) -> tuple:
    ivs = mon.get("ivs")
    ivs_t = tuple(sorted(ivs.items())) if ivs else None
    return (_canon(mon["species"]), mon["level"], mon.get("item"), mon.get("nature"), ivs_t)


def _json_pack_full_multiset() -> Counter:
    data = json.loads(_JSON_PACK.read_text(encoding="utf-8"))
    return Counter(_json_pack_mon_key(mon) for t in data["trainers"].values() for mon in t["party"])


def _json_pack_moves_multiset() -> Counter:
    data = json.loads(_JSON_PACK.read_text(encoding="utf-8"))
    c: Counter = Counter()
    for t in data["trainers"].values():
        for mon in t["party"]:
            moves = mon.get("moves")
            c[_json_pack_mon_key(mon) + (tuple(moves) if moves else None,)] += 1
    return c


def _js_setdex_dict() -> dict:
    text = _JS_SETDEX.read_text(encoding="utf-8")
    lines = [ln for ln in text.splitlines() if not ln.strip().startswith("//")]
    text = "\n".join(lines).strip()
    assert text.startswith("var "), _JS_SETDEX
    body = text[text.index("=") + 1:].strip().rstrip(";")
    return json.loads(body)


def _js_setdex_multiset() -> Counter:
    dex = _js_setdex_dict()
    c: Counter = Counter()
    for species, sets in dex.items():
        for entry in sets.values():
            c[(_canon(species), entry["level"])] += 1
    return c


def test_json_pack_identity_matches_lock_pin():
    data = json.loads(_JSON_PACK.read_text(encoding="utf-8"))
    assert data["source"]["commit"] == _PIN


def test_gen3_exp_trainers_json_matches_pinned_source():
    src = _need_source()
    assert _json_pack_multiset() == _source_species_level_multiset(src)


def test_emerald_expansion_js_matches_pinned_source():
    src = _need_source()
    assert _js_setdex_multiset() == _source_species_level_multiset(src)


def test_gen3_exp_trainers_json_full_fidelity_matches_pinned_source():
    """species+level+item+nature+ivs, whole-file, full equality (OMP cx-081c78d3 F3)."""
    src = _need_source()
    assert _json_pack_full_multiset() == _source_full_multiset(src)


def test_explicit_moves_in_source_all_appear_in_the_json_pack():
    """Every mon whose .moves the source spells out explicitly must appear -- species, level,
    item, nature, ivs AND that exact move list -- in the JSON pack at least as many times as the
    source has it. A subset check, not full-multiset equality: the pack also carries
    level-up-learnset-derived move lists (no explicit .moves in source) mixed into the same
    "moves" field, and nothing in the pack says which branch produced any one entry."""
    src = _need_source()
    explicit = _source_explicit_moves_multiset(src)
    pack = _json_pack_moves_multiset()
    missing = explicit - pack
    assert not missing, dict(missing)


def test_default_derived_moves_match_a_learnset_sample():
    """A sample of mons the source gives NO .moves for (GiveBoxMonInitialMoveset's level-up
    learnset default applies instead): recompute the expected move list independently
    (server.adapters.gen3_frlge.default_moves() over the same learnset tables, not
    tools/gen_gen3_exp_trainers.py's own default_moveset() closure) and confirm the JSON pack
    has a matching entry for each sampled (species, level)."""
    src = _need_source()
    text = re.sub(r"#line \d+\n\s*", "", (src / "src/data/trainers.h").read_text(encoding="utf-8"))
    species_ids = enum_values((src / "include/constants/species.h").read_text(encoding="utf-8"), "SPECIES_")
    move_ids = enum_values((src / "include/constants/moves.h").read_text(encoding="utf-8"), "MOVE_")
    sp_learnset_sym = parse_species_learnset_symbols(src)
    learnset_tables = parse_learnset_tables(src)
    adapter = Gen3ExpansionAdapter(rom_type=ROM_TYPE)

    sample: list[tuple[str, int]] = []
    for m in re.finditer(r"\.species\s*=\s*(SPECIES_\w+),.{1,300}?\.lvl\s*=\s*(\d+),", text, re.S):
        window = text[m.start():m.start() + 700]
        nxt = window.find(".species", len(".species"))
        if nxt != -1:
            window = window[:nxt]
        if re.search(r"\.moves\s*=", window) or m[1] not in sp_learnset_sym:
            continue
        sample.append((m[1], int(m[2])))
        if len(sample) >= 25:
            break
    assert sample, "expected at least one default-moveset mon with a known learnset in this build"

    pack_moves: dict[tuple[str, int], set] = {}
    for t in json.loads(_JSON_PACK.read_text(encoding="utf-8"))["trainers"].values():
        for mon in t["party"]:
            key = (_canon(mon["species"]), mon["level"])
            pack_moves.setdefault(key, set()).add(tuple(mon.get("moves") or ()))

    for sp_macro, level in sample:
        sym = sp_learnset_sym[sp_macro]
        expected_macros = default_moves(learnset_tables.get(sym, []), level)
        expected = tuple(adapter.calc_name("move", adapter.move_name(move_ids[mv])) for mv in expected_macros)
        key = (_canon(adapter.calc_species(species_ids[sp_macro])), level)
        assert expected in pack_moves.get(key, set()), (sp_macro, level, expected, pack_moves.get(key))


