# -- Gen 4 vectors (independent decoder from the Gen 4 worktree) ---------------------------------------------
def load_gen4_codec():
    path = GEN4_WT / "server/adapters/gen4_codec.py"
    if not path.is_file():
        pytest.skip(f"Gen 4 oracle not found: {path} (override the worktree with SLINK_GEN4_WT)")
    spec = importlib.util.spec_from_file_location("_gen4_codec_ro", path)
    m = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = m  # dataclasses needs the module registered
    spec.loader.exec_module(m)
    return m


def build_plain(codec, pid: int, party: bool) -> bytes:
    """tests/unit/test_gen4_pk4_lua.py::build_plain (structure only: a plausible PK4 record)."""
    p = bytearray(codec.PARTY_MON_SIZE if party else codec.BOX_MON_SIZE)
    a, b, c, d = (8 + 0x20 * i for i in range(4))
    struct.pack_into("<IHH", p, 0, pid, 0, 0)
    struct.pack_into("<HHII", p, a, 250, 5, 0x1234_5678, 1_000_000)
    p[a + 0x0C : a + 0x10] = bytes((70, 0x2A, 3, 2))
    struct.pack_into("<4H", p, b, 33, 45, 52, 0)
    struct.pack_into("<I", p, b + 0x10, 0x8000_0000 | 0x1F | (7 << 5))
    struct.pack_into("<11H", p, c, *codec.encode_name("Lugi", 11))
    struct.pack_into("<8H", p, d, *codec.encode_name("RED", 8))
    if party:
        struct.pack_into("<IBBHHHHHHH", p, 0x88, 0, 50, 0, 100, 150, 90, 80, 70, 60, 50)
    return bytes(p)


@pytest.mark.parametrize("row", range(32))
def test_gen4_synthetic_vectors_every_shuffle_row(mod, row):
    codec = load_gen4_codec()
    pid = (0xABCD_0001 & ~0x3E000) | (row << 13)
    for party in (True, False):
        plain = build_plain(codec, pid, party)
        raw = (codec.encrypt_party if party else codec.encrypt_box)(plain)
        n = len(plain)
        assert (oracle.encrypt_party(plain, n) if party else oracle.encrypt_stored(plain)) == raw
        want = (codec.decrypt_party if party else codec.decrypt_box)(raw)
        got, _ = mod.decrypt_party(raw, n) if party else mod.decrypt_stored(raw)
        assert lua_bytes(got) == want
        assert lua_bytes(mod.encrypt_party(got, n) if party else mod.encrypt_stored(got)) == raw
        assert (mod.pid(got), mod.otid(got)) == (pid, 0x1234_5678)
        assert mod.mon_key(got) == codec.mon_key(pid, 0x1234_5678)


@pytest.mark.parametrize("which,default,profile", [
    ("hg", "Pokemon - HeartGold Version (USA).SaveRAM", "hgss"),
    ("ss", "Pokemon - SoulSilver Version (USA).SaveRAM", "hgss"),
    ("pt", "Pokemon - Platinum Version (USA).SaveRAM", "pt"),
])
def test_gen4_real_save_records(mod, which, default, profile):
    codec = load_gen4_codec()
    env = f"SLINK_GEN4_{which.upper()}_SAVE"
    path = Path(os.environ.get(env) or SAVE_DIR / default)
    if not path.is_file():
        pytest.skip(f"{which} battery save not found: {path} (override with {env})")
    save = codec.parse_save(path.read_bytes(), profile)
    p = save.profile
    recs = []
    _, cur = struct.unpack_from("<II", save.general, p.party_off)
    for i in range(cur):
        o = p.party_off + 8 + i * codec.PARTY_MON_SIZE
        recs.append((True, save.general[o : o + codec.PARTY_MON_SIZE]))
    for b in range(p.box_count):
        for s in range(30):
            o = p.boxes_off + b * p.box_stride + s * codec.BOX_MON_SIZE
            recs.append((False, save.pc[o : o + codec.BOX_MON_SIZE]))
    checked = 0
    for party, raw in recs:
        if codec.is_empty_slot(raw):
            continue
        want = (codec.decrypt_party if party else codec.decrypt_box)(raw)
        n = len(raw)
