@pytest.mark.parametrize("party_len", [GEN4, GEN5])
def test_pseudo_random_records_agree_and_round_trip(mod, party_len):
    rng = random.Random(0x5EED_0000 + party_len)
    for n in range(256):
        pid = rng.getrandbits(32) if n >= 32 else (rng.getrandbits(32) & ~0x3E000) | (n << 13)
        flags = 4 if n % 5 == 0 else 0  # bit 2 = bad egg, a legitimate stored state
        plain = random_plain(rng, party_len, pid, flags)
        stored = oracle.encrypt_party(plain, party_len)
        assert struct.unpack_from("<H", stored, 4)[0] == flags  # encrypt preserves bit 2
        # Lua decrypt == oracle decrypt, header included
        want, info = oracle.decrypt_party(stored, party_len)
        assert same_but_checksum(want, plain)
        got, linfo = mod.decrypt_party(stored, party_len)
        assert lua_bytes(got) == want
        assert linfo.bad_egg == info["bad_egg"] == bool(flags) and linfo.decrypted is False and linfo.checksum_ok is True
        assert linfo.pid == info["pid"] == pid and linfo.row == info["row"] and linfo.checksum == info["checksum"]
        assert py(linfo.order) == info["order"]
        # Lua encrypt == oracle encrypt (checksum recomputed identically), and the round trip is exact
        assert lua_bytes(mod.encrypt_party(want, party_len)) == stored
        assert lua_bytes(mod.encrypt_party(got, party_len)) == stored
        # the 0x88 stored forms (a box record) agree too
        box = oracle.encrypt_stored(plain[:0x88])
        assert box == stored[:0x88]
        bgot, _ = mod.decrypt_stored(box)
        assert lua_bytes(bgot) == oracle.decrypt_stored(box)[0] == want[:0x88]
        assert lua_bytes(mod.encrypt_stored(bgot)) == box
        # strings and 1-based arrays are interchangeable inputs; outputs are fresh arrays


