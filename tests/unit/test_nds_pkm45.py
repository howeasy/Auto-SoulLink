# -- hand-computed stored layout (Lua only): pins the shuffle DIRECTION with no optional input present ------------
def lcg_local(data: bytes, seed: int) -> bytes:
    out = bytearray()
    for i in range(0, len(data), 2):
        seed = (seed * 0x41C64E6D + 0x6073) & 0xFFFFFFFF
        out += struct.pack("<H", struct.unpack_from("<H", data, i)[0] ^ (seed >> 16))
    return bytes(out)


# Read off the cartridge table indexed sv*4 + logical block (bytes at sv*4: 3 -> 00 60 20 40,
# 12 -> 20 40 00 60, 17 -> 60 40 00 20): the stored sequence of logical blocks, slot 0 first. All three are
# non-involutions, so a flipped direction cannot pass.
STORED_SEQUENCE = {3: "ACDB", 12: "CABD", 17: "CDBA"}
FILL = {"A": 0xA1, "B": 0xB2, "C": 0xC3, "D": 0xD4}


@pytest.mark.parametrize("row", sorted(STORED_SEQUENCE))
def test_shuffle_direction_pinned_without_any_optional_input(mod, row):
    pid = (row << 13) | 0x123
    seq = STORED_SEQUENCE[row]
    header = struct.pack("<IHH", pid, 0, 0)
    logical = b"".join(bytes([FILL[c]]) * 0x20 for c in "ABCD")
    # encrypt: strip the cipher by hand and read the stored order
    stored = lua_bytes(mod.encrypt_stored(header + logical))
    body = lcg_local(stored[8:], struct.unpack_from("<H", stored, 6)[0])
    assert "".join({v: k for k, v in FILL.items()}[body[s * 0x20]] for s in range(4)) == seq
    # decrypt: hand-build the stored record from the layout, expect logical A,B,C,D back
    hand = b"".join(bytes([FILL[c]]) * 0x20 for c in seq)
    csum = sum(struct.unpack("<64H", hand)) & 0xFFFF
    rec = struct.pack("<IHH", pid, 0, csum) + lcg_local(hand, csum)
    got, info = mod.decrypt_stored(rec)
    assert lua_bytes(got)[8:] == logical and info.row == row


