def random_plain(rng: random.Random, party_len: int, pid: int | None = None, flags: int = 0) -> bytes:
    p = bytearray(rng.randbytes(party_len))
    if pid is not None:
        struct.pack_into("<I", p, 0, pid)
    struct.pack_into("<H", p, 4, flags)  # default 0; bits 0-1 clear = the encrypted representation
    return bytes(p)


def opts(rt, **kw):
    return rt[0].table_from(kw)


def same_but_checksum(a: bytes, b: bytes) -> bool:
    return a[:6] == b[:6] and a[8:] == b[8:]  # encryption recomputes the checksum header word


