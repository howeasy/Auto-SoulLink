# -- flags word: bad egg (bit 2) and the game's own "decrypted" marker (bits 0-1) --------------------------------
def R(v):
    """A Lua multi-return as a tuple (lupa gives a bare value for a single return)."""
    return v if isinstance(v, tuple) else (v,)


def make_decrypted(stored: bytes, party_len: int, bits: int = 3) -> bytes:
    """What the game's Decrypt() leaves in RAM: body+tail XOR-plain, blocks still SHUFFLED, flags bits 0-1 set
    (docs/gen5/research/rom_code_anchors.md:66,214). Built from the oracle's logical plain + its block order."""
    plain, info = oracle.decrypt_party(stored, party_len)
    body = bytearray(0x80)
    for which, o in enumerate(oracle.block_order(info["pid"])):
        body[o : o + 0x20] = plain[8 + which * 0x20 : 8 + (which + 1) * 0x20]
    flags = info["flags"] | bits
    return plain[:4] + struct.pack("<H", flags) + plain[6:8] + bytes(body) + plain[0x88:]


@pytest.mark.parametrize("party_len", [GEN4, GEN5])
def test_bad_egg_is_reported_preserved_and_never_an_error(mod, party_len):
    plain = random_plain(random.Random(21), party_len, 0x0001_4321, flags=0x0004)
    stored = oracle.encrypt_party(plain, party_len)
    got, info = mod.decrypt_party(stored, party_len)
    assert info.bad_egg is True and info.decrypted is False and info.flags == 4
    assert lua_bytes(got) == oracle.decrypt_party(stored, party_len)[0]
    assert oracle.decrypt_party(stored, party_len)[1]["bad_egg"] is True
    assert struct.unpack_from("<H", lua_bytes(mod.encrypt_party(got, party_len)), 4)[0] == 4  # never repaired
    clean, cinfo = mod.decrypt_party(oracle.encrypt_party(random_plain(random.Random(22), party_len, 5), party_len), party_len)
    assert cinfo.bad_egg is False
    # bad egg + decrypted marker: the refusal is "locked", not "checksum"
    dec = make_decrypted(stored, party_len)
    assert struct.unpack_from("<H", dec, 4)[0] == 7
    assert R(mod.decrypt_party(dec, party_len)) == (None, "locked")


@pytest.mark.parametrize("bits", [1, 2, 3])
@pytest.mark.parametrize("party_len", [GEN4, GEN5])
def test_decrypted_marker_is_refused_by_default_and_opt_in_decodes(rt, mod, party_len, bits):
    plain = random_plain(random.Random(31 + bits), party_len, (7 << 13) | 0x55)
    stored = oracle.encrypt_party(plain, party_len)
    want, winfo = oracle.decrypt_party(stored, party_len)
    dec = make_decrypted(stored, party_len, bits)
    assert R(mod.decrypt_party(dec, party_len)) == (None, "locked")
    assert R(mod.decrypt_stored(dec[:0x88])) == (None, "locked")
    assert R(mod.decrypt_party(dec, party_len, opts(rt, allow_decrypted=False))) == (None, "locked")
    with pytest.raises(oracle.PkmError) as e:
        oracle.decrypt_party(dec, party_len)
    assert e.value.reason == "locked"
    got, info = mod.decrypt_party(dec, party_len, opts(rt, allow_decrypted=True))
    ogot, oinfo = oracle.decrypt_party(dec, party_len, allow_decrypted=True)
    assert lua_bytes(got) == ogot == want[:4] + struct.pack("<H", bits) + want[6:]  # logical blocks, plain tail
    assert info.decrypted is True and info.checksum_ok is True and oinfo["decrypted"] is True
    assert info.flags == oinfo["flags"] == bits and py(info.order) == oinfo["order"] == winfo["order"]
    # box form too
    bgot, _ = mod.decrypt_stored(dec[:0x88], opts(rt, allow_decrypted=True))
    assert lua_bytes(bgot) == ogot[:0x88]
    # encrypt always clears bits 0-1, and the result decrypts back by default
    again = lua_bytes(mod.encrypt_party(got, party_len))
    assert struct.unpack_from("<H", again, 4)[0] & 0x3 == 0 and again == stored
    assert oracle.encrypt_party(ogot, party_len) == stored
    assert lua_bytes(mod.decrypt_party(again, party_len)[0]) == want
    assert struct.unpack_from("<H", lua_bytes(mod.encrypt_stored(bgot)), 4)[0] & 0x3 == 0


def test_decrypted_mode_reports_a_stale_checksum_instead_of_enforcing_it(rt, mod):
    stored = oracle.encrypt_party(random_plain(random.Random(41), GEN4, 0x0002_0099), GEN4)
