class PretAbsent(Exception):
    """The pinned pokeheartgold clone is not on this machine (exit 2 / test skip)."""


class PretMismatch(Exception):
    """The clone exists but is not the pinned, clean checkout (exit 1 / test FAIL)."""


class AcquisitionAbsent(Exception):
    """The generated acquisition inventory is missing (exit 1): the gift-area list cannot be derived."""


class GiftAreaOnWildMap(Exception):
    """A gift site resolved to an area that owns a wild-encounter map (exit 1, fail closed)."""


