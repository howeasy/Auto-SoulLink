#!/usr/bin/env python3
"""gen_gen4_area_map.py -- HGSS area map + location table from pinned pret/pokeheartgold.

Writes (both from the same parse, one provenance block each):
  data/games/gen4_hgss/area_map.json   area_id -> display/maps, plus map_id -> area_id and gift_areas
  data/games/gen4_hgss/locations.json  map_id -> const/token/mapsec/region/type/area
  data/games/gen4_hge/area_map.json    the SAME map for the hg-engine pack, PROVEN equal to HGSS's on the
  data/games/gen4_hge/locations.json   two pinned ROMs (see HGE_PROOF below), not assumed

`gift_areas` (the `ids` list) is derived from the PACK's own acquisition inventory
(data/games/<pack>/acquisition.json, each generated by tools/gen_gen4_acquisition.py from the same pin):
the areas a scripted starter/gift/egg/loan reaches where NO map in the area owns a
wildEncounterBank. The client drops `no_catch` for an area in that list (lua/gen4/poll_events.lua:
415-418), so a list that covered a route would swallow a real failed encounter -- hence the split is
on the map's own wildEncounterBank, a `static` site is excluded (a static IS a WildBattle; Gen 3 makes
the same call at tools/gen_area_map.py:736-742), and a contradiction raises instead of picking a side.

gen4_hge gets the same two files, from the same parse, with the derivation unchanged -- and the generator
PROVES they are valid for the fork instead of assuming it. The fork's own SOURCE still cannot supply an
area (no MAPSEC_*, no src/data/map_headers.h, no `// MAP_<token>` comments, no files/msgdata/msg tree),
but its ROM carries the finished table: `sMapHeaders` (540 MapHeader records -- wildEncounterBank,
areaDataBank, mapsec, regionNo, mapType) and msg 279 (the area names, indexed by mapsec). Both are read
from BOTH pinned ROMs on every run and must be byte-identical; a present-but-different span is a FAIL and
nothing is written, an absent ROM is an OPEN skip (exit 2). So hge needs no pret oracle BEYOND the HGSS
map it is proven to be -- the file it ships records that proof (full sha256 of both spans, both ROM sha1s,
the address and the size) beside the pret provenance. `gift_areas` reads the hge pack's OWN
acquisition.json, never gen4_hgss's.

Source (pokeheartgold @ the commit pinned in data/gen4_sources.lock.json, never a ROM text dump):
  include/constants/maps.h          MAP_* id and the MAP_<token> comment
  src/data/map_headers.h            .mapsec .regionNo .mapType .wildEncounterBank per map
  include/constants/map_sections.h  MAPSEC_* ids
  files/msgdata/msg/msg_0279.gmm    area names, indexed by mapsec (src/field/draw_map_name.c)
  include/constants/safari.h        the 12 Safari areas (D10: Safari counts per area)

Area rule: an area is a map section (mapsec) -- every map sharing a mapsec shares a Soul Link area
(Union Cave 1F/B1F/B2F, Elm's Lab inside New Bark Town, ...). The area_id is the slug of the English
name in msg 0279. D10 overrides: the Bug-Catching Contest map is its own area, and the Safari Zone
gets one sub-area per Safari area (the area a position falls in is chosen at runtime from the
player's coordinates and area set, so those sub-areas own no static map).

This module is also the shared helper layer for gen_gen4_{encounters,trainers,acquisition}.py.

Usage:
  python tools/gen_gen4_area_map.py            # write both packs
  python tools/gen_gen4_area_map.py --check    # regenerate in memory, diff vs committed (exit 1 on drift)
  python tools/gen_gen4_area_map.py --path heartgold_hge=<rom>   # point the hge proof at another build
Exit: 0 ok, 1 drift / wrong pret commit / hge map data that is NOT the HGSS map, 2 the pret clone or a
pinned ROM is absent (OPEN, nothing written -- the hge pair is never written unproven).
"""

