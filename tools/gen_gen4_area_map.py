def documents(m: dict, *, note: str, prov: dict, acq_path: Path, depth: int = 2) -> dict[str, str]:
    """The two emitted documents, from ONE model. Both packs come through here, so gen4_hge cannot
    differ from gen4_hgss in any field except the provenance the caller hands in."""
    maps, areas = m["maps"], m["areas"]

    area_doc = {
        "_note": note + " areas: area_id -> display/maps (map ids). maps: map_id -> area_id (null = not a Soul Link place, see unmapped_maps).",
        "_schema": "gen4-hgss-area-map-v1",
        "source": prov,
        "rules": {
            "area": "one area per map section (mapsec); display = msg 0279[mapsec]",
            "bug_contest": f"{BUG_CONTEST_MAP} is its own area (D10); a kept bug is the catch, awarded at the result",
            "safari": "Safari Zone is one sub-area per Safari area (D10); area resolved at runtime, sub-areas own no static map",
            "gift_areas": GIFT_RULE,
        },
        "areas": {aid: areas[aid] for aid in sorted(areas)},
        "maps": {str(mid): m["map_area"].get(mid) for mid in sorted(maps.rows)},
        "unmapped_maps": {str(mid): why for mid, why in sorted(m["unmapped"].items())},
        "gift_areas": gift_areas(m, load_acquisition(acq_path), acq_path),
    }
    loc_doc = {
        "_note": note + " Per-map location facts (HUD/status page): the name shown in game is the mapsec name.",
        "_schema": "gen4-hgss-locations-v1",
        "source": prov,
        "locations": {
            str(mid): {
                "const": row["const"],
                "token": row["token"],
                "mapsec": row["mapsec"],
                "name": m["sec_name"][m["sec_ids"][row["mapsec"]]],
                "region": row["region"],
                "map_type": row["map_type"],
                "enc_bank": row["enc_bank"],
                "area": m["map_area"].get(mid),
            }
            for mid, row in sorted(maps.rows.items())
        },
    }
    return {"area_map.json": dumps(area_doc, depth), "locations.json": dumps(loc_doc, depth)}


def build(clone: Path) -> dict[str, str]:
    return documents(build_model(clone), note=NOTE, prov=provenance(clone, GENERATOR, INPUTS), acq_path=ACQUISITION)


# --------------------------------------------------------------------------- the hge proof
def hge_inputs(overrides: dict[str, str] | None = None):
    """The ROM paths exactly as tools/gen_gen4_pack.py resolves them (gen4_pins locations, then
    SLINK_GEN4_<KEY>, then --path), so both Gen 4 generators have ONE input resolver."""
    return pack.default_inputs(overrides or {})


def area_name_member(rom: Path, member: int = AREA_NAMES_MSG) -> bytes:
    """The raw bytes of one message-NARC member (ndspy), read whole: equality is decided on the bytes."""
    import ndspy.narc
    import ndspy.rom

    narc = ndspy.narc.NARC(ndspy.rom.NintendoDSRom.fromFile(str(rom)).getFileByName(AREA_NAMES_NARC))
    if member >= len(narc.files):
        raise HgeMapDrift(f"{AREA_NAMES_NARC} in {rom} holds {len(narc.files)} members, not {member + 1}: "
                          "the area-name bank is not where this generator reads it")
    return bytes(narc.files[member])


def map_header_spans(images: dict) -> dict[str, bytes]:
    """The sMapHeaders span out of each ROM's ARM9 image, addressed BY IMAGE (never by address alone)."""
    return {key: img.read(MAP_HEADERS_IMAGE, MAP_HEADERS_ADDR, MAP_HEADERS_SIZE) for key, img in sorted(images.items())}


def _sha(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def require_identical(blobs: dict[str, bytes], what: str) -> None:
    """Fail closed: two ROMs must agree byte for byte. Full digests, no prefixes, in the message."""
    rows = [(key, blob, _sha(blob)) for key, blob in sorted(blobs.items())]
    if len({digest for _, _, digest in rows}) != 1:
        detail = ", ".join(f"{key} {len(blob)} B sha256 {digest}" for key, blob, digest in rows)
        raise HgeMapDrift(f"{what} is NOT byte-identical between the vanilla HG and the hge ROM -- {detail}")


def hge_proof(inputs=None) -> dict:
    """Read both spans out of BOTH pinned ROMs, require byte equality, and return the provenance block.

    Fail closed on a present-but-different span (HgeMapDrift, exit 1); an absent input is a named OPEN
    skip (HgeRomAbsent, exit 2). There is no path that emits the hge files without this passing."""
    inputs = hge_inputs() if inputs is None else inputs
    try:
        lock = pack.load_lock(inputs)
        roms = {key: pack.verify_rom(inputs, lock, key) for key in ("heartgold", "heartgold_hge")}
        images = {
            # the two sources tools/gen_gen4_pack.py uses (Images.from_rom / ARM9_BYTES_NOTE): HG through
            # ndspy's DECOMPRESSED static image, hge through the raw uncompressed rom.arm9.
            "heartgold": pack.load_images(inputs.paths["heartgold"]),
            "heartgold_hge": pack.load_images(inputs.paths["heartgold_hge"], raw_arm9=True),
        }
        spans = map_header_spans(images)
        names = {key: area_name_member(inputs.paths[key], AREA_NAMES_MSG) for key in sorted(images)}
    except pack.Skip as exc:
        raise HgeRomAbsent(str(exc)) from exc
    except pack.Fail as exc:
        raise HgeMapDrift(str(exc)) from exc
    except (OSError, ValueError, KeyError) as exc:
        raise HgeMapDrift(f"cannot read the map data out of the pinned ROMs: {exc}") from exc
    require_identical(spans, f"{MAP_HEADERS_SYMBOL} ({MAP_HEADERS_ADDR:#010x}+{MAP_HEADERS_SIZE:#x})")
    require_identical(names, f"{AREA_NAMES_NARC} member {AREA_NAMES_MSG} (area names)")
    return {
        "claim": HGE_PROOF,
        "identical": True,
        "map_headers": {
            "symbol": MAP_HEADERS_SYMBOL,
            "image": MAP_HEADERS_IMAGE,
            "address": f"{MAP_HEADERS_ADDR:#010x}",
            "size": MAP_HEADERS_SIZE,
            "struct_size": MAP_HEADER_SIZE,
            "count": MAP_HEADER_COUNT,
            "sha256": {key: _sha(blob) for key, blob in sorted(spans.items())},
            "cite": MAP_HEADERS_CITE,
        },
        "area_names": {
            "narc": AREA_NAMES_NARC,
            "member": AREA_NAMES_MSG,
            "size": len(names["heartgold"]),
            "sha256": {key: _sha(blob) for key, blob in sorted(names.items())},
            "cite": "msg 0279 = area names, indexed by mapsec (pokeheartgold src/field/draw_map_name.c)",
        },
        "roms": {key: {"sha1": row["sha1"], "sha256": row["sha256"], "size_bytes": row["size_bytes"]}
                 for key, row in sorted(roms.items())},
        "method": ("both spans are read from both ROMs on every run and compared whole; HG through ndspy "
                   "loadArm9().sections[0] (the DECOMPRESSED static image, never the compressed rom.arm9), "
                   "hge through the raw uncompressed rom.arm9 -- the two sources tools/gen_gen4_pack.py "
                   "uses. Each ROM's identity is checked against data/gen4_sources.lock.json before either "
                   "is read, so a rebuilt or substituted ROM cannot pass as the pinned one."),
    }


def build_hge(clone: Path, inputs=None) -> dict[str, str]:
    """The same two documents for gen4_hge: same parse, same derivation, recorded proof, own inventory.

    Fails before anything is written -- a map-id range that no longer matches the table, a ROM that is not
    the pinned one, or a fork whose map data has drifted from HGSS's all raise instead of emitting a
    plausible file. depth 3 keeps the provenance block readable (the HGSS files stay at 2, unchanged)."""
    m = build_model(clone)
    if len(m["maps"].rows) != MAP_HEADER_COUNT:
        raise HgeMapDrift(f"the pinned clone parses {len(m['maps'].rows)} maps but {MAP_HEADERS_SYMBOL} holds "
                          f"{MAP_HEADER_COUNT} records; MAP_HEADERS_ADDR/SIZE no longer describe this pin")
    note = NOTE + (" Areas and names are the HGSS ones, proven byte-identical in the fork's ROM -- see "
                   "source.hge_proof, which records the full sha256 of both spans and both ROM sha1s.")
    prov = {**provenance(clone, GENERATOR, INPUTS), "hge_proof": hge_proof(inputs)}
    return documents(m, note=note, prov=prov, acq_path=HGE_ACQUISITION, depth=3)


def main() -> int:
    # The failures this file owns are exit 1, not the clone's: a missing inventory, a gift area covering a
    # wild map, and hge map data that is not the HGSS map. So cli()'s codes hold: 2 = a pinned input is
    # absent (OPEN, nothing written), 1 = drift or a FAIL.
    try:
        return cli(build, __doc__.splitlines()[0],
                   extra=lambda clone, overrides: [(HGE_OUT_DIR, build_hge(clone, hge_inputs(overrides)))])
    except (AcquisitionAbsent, GiftAreaOnWildMap) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
